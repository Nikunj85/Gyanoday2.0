'use server'

import { requireUser } from '@/lib/auth/guards'
import { smartNotesAiService } from '@/services/ai/smart-notes-ai-service'
import { contentLanguageKey, resolveStudentContentLanguage, textMatchesLanguage } from '@/lib/ai/language'
import { supabaseAdmin as admin } from '@/lib/supabase/admin'

/**
 * Generates Smart Notes for a chapter and caches them on the `chapters`
 * row so the next student to open this chapter gets them instantly
 * instead of waiting on a fresh AI generation.
 *
 * This is triggered by any student opening the Smart Notes tab for a
 * chapter that doesn't have notes yet — it is NOT an admin content edit,
 * it's a system-level cache-fill (same category of write as caching a
 * chapter's `file_id`/`vector_store_id` in chapter-server-service.ts).
 * The `chapters` table's RLS only allows admins to UPDATE rows, so this
 * write goes through the service-role client (`supabaseAdmin`), the same
 * pattern already used for those other generated/cached columns — a
 * regular student session would have the RLS write silently rejected.
 */
export async function generateAndSaveSmartNotes(chapterId: string) {
  if (!chapterId) {
    throw new Error('Chapter ID is required')
  }

  // Must be signed in (this spends AI credits and writes with the service role).
  const user = await requireUser()
  const { data: profile } = await admin.from('users').select('language').eq('id', user.id).maybeSingle()
  const medium = profile?.language || 'en'
  const { data: chapterLanguageData } = await admin.from('chapters').select('subject:subjects(name)').eq('id', chapterId).maybeSingle()
  const relatedSubject: any = Array.isArray((chapterLanguageData as any)?.subject) ? (chapterLanguageData as any).subject[0] : (chapterLanguageData as any)?.subject
  const contentLanguage = resolveStudentContentLanguage(medium, relatedSubject?.name)
  const languageKey = contentLanguageKey(contentLanguage)

  // Already generated by someone else? Return the cached notes instead of paying again.
  const { data: existing } = await admin
    .from('chapters')
    .select('smart_notes')
    .eq('id', chapterId)
    .maybeSingle()
  const stored: any = existing?.smart_notes

  // Cached notes are only reused when they really are in the required language.
  // Old (legacy) caches had no language tag, so they are verified by script instead of trusted -
  // that is how Gujarati notes were being served for the English subject.
  const byLanguage: Record<string, any> = { ...(stored?._byLanguage || {}) }
  const legacy = Array.isArray(stored) ? null : stored?.core_layer ? stored : null
  if (legacy) {
    for (const key of ['en', 'hi', 'gu'] as const) {
      const label = key === 'hi' ? 'Hindi' : key === 'gu' ? 'Gujarati' : 'English'
      if (!byLanguage[key] && textMatchesLanguage(legacy, label)) {
        byLanguage[key] = legacy
        break
      }
    }
  }
  const cachedNotes = byLanguage[languageKey]
  if (cachedNotes && textMatchesLanguage(cachedNotes, contentLanguage)) return cachedNotes
  delete byLanguage[languageKey] // wrong-language cache for this slot -> regenerate

  const notes = await smartNotesAiService.generateSmartNotes(chapterId, medium)

  const { error } = await admin
    .from('chapters')
    .update({ smart_notes: { _byLanguage: { ...byLanguage, [languageKey]: notes } } })
    .eq('id', chapterId)

  if (error) {
    throw new Error(`Failed to save Smart Notes: ${error.message}`)
  }

  return notes
}